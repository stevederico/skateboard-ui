#!/usr/bin/env node
// Generates icons/index.tsx: a vendored subset of lucide-react.
//
// Collects every icon name the package imports (from 'lucide-react' or from the
// local icons module), copies each icon's SVG node data from an installed
// lucide-react, and writes one named export per icon so bundlers tree-shake it.
//
// lucide-react is not a dependency. To regenerate:
//   npm i --no-save lucide-react@0.546.0
//   node scripts/vendor-lucide-icons.js
//   npm uninstall --no-save lucide-react   (or delete node_modules/lucide-react)
//
// Optional arg: path to a lucide-react package directory.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = process.argv[2] ?? join(root, 'node_modules', 'lucide-react');
if (!existsSync(join(pkgDir, 'package.json'))) {
  console.error(`vendor-lucide-icons: lucide-react not found at ${pkgDir}`);
  process.exit(1);
}
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const esm = join(pkgDir, 'dist', 'esm');

// export name -> icon file stem, from lucide-react's barrel.
const nameToFile = new Map();
const barrel = readFileSync(join(esm, 'lucide-react.js'), 'utf8');
for (const m of barrel.matchAll(/export \{([^}]*)\} from '\.\/icons\/([^']+)\.js';/g)) {
  for (const part of m[1].split(',')) {
    const alias = part.trim().match(/^default as (\w+)$/);
    if (alias) nameToFile.set(alias[1], m[2]);
  }
}

// Icon names imported anywhere in the package source.
const SRC_DIRS = ['App.tsx', 'index.ts', 'components', 'ui', 'hooks', 'shadcn'];
const IMPORT_RE = /import\s*\{([^}]*)\}\s*from\s*["'](?:lucide-react|(?:\.\.?\/)+icons\/index\.js)["']/g;
const names = new Set();
function scan(p) {
  if (!existsSync(p)) return;
  if (statSync(p).isDirectory()) {
    for (const e of readdirSync(p)) scan(join(p, e));
    return;
  }
  if (!/\.tsx?$/.test(p)) return;
  for (const m of readFileSync(p, 'utf8').matchAll(IMPORT_RE)) {
    for (const n of m[1].split(',').map((s) => s.trim()).filter(Boolean)) {
      if (n.startsWith('type ') || n.includes(' as ')) throw new Error(`unsupported icon import "${n}" in ${p}`);
      names.add(n);
    }
  }
}
for (const d of SRC_DIRS) scan(join(root, d));

const toPascal = (s) => s.replace(/^([a-z])|[\s-_]+(\w)/g, (_, a, b) => (a ?? b).toUpperCase());
const toKebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

// Group names by icon file. Canonical export = PascalCase of the file stem.
const byFile = new Map();
for (const n of [...names].sort()) {
  const file = nameToFile.get(n);
  if (!file) throw new Error(`unknown lucide icon "${n}"`);
  if (!byFile.has(file)) byFile.set(file, new Set());
  byFile.get(file).add(n);
}

const decls = [];
const aliases = [];
for (const file of [...byFile.keys()].sort()) {
  const mod = await import(pathToFileURL(join(esm, 'icons', `${file}.js`)).href);
  const node = mod.__iconNode;
  const canonical = toPascal(file);
  const classes = [...new Set([`lucide-${toKebab(canonical)}`, `lucide-${file}`])].join(' ');
  const exported = byFile.get(file);
  const primary = exported.has(canonical) ? canonical : [...exported][0];
  decls.push(
    `export const ${primary} = /* @__PURE__ */ createIcon('${canonical}', '${classes}', ${JSON.stringify(node)});`
  );
  for (const n of exported) if (n !== primary) aliases.push(`export const ${n} = ${primary};`);
}

